export function toDistrictCode(name: string): string | null {
  const key = name
    .toLowerCase()
    .replace(/\bdistrict\b/g, "")
    .replace(/[^a-z]/g, "");
  const code = ALIASES[key] ?? key;
  return DISTRICT_CODES.has(code) ? code : null;
}
